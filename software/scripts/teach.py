#!/usr/bin/env python3
"""Teach / nudge station poses on the real bench (or in the sim) and save offsets.

  python3 software/scripts/teach.py --backend real pourer rack_developer
  python3 software/scripts/teach.py --backend sim transfer carousel_pick

Moves the arm to the planned grasp pose with the jaw open, then takes single-key nudges:
  w/s  +-2 mm along world X     a/d  +-2 mm along world Y     r/f  +-2 mm along world Z
  W/S/A/D/R/F  the same in 0.5 mm steps      c  close jaw (classify)      o  open jaw
  g  re-solve IK at the nudged target and move there     p  print pose
  ENTER  save the offset to bench.yaml calibration.station_offsets_mm     q  quit
The saved offset is applied by motion/stations.py the next time poses are planned, for both
backends - so what you teach on the bench is what the sim plans with too.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import numpy as np
import yaml

from bench.config import BENCH_YAML, load
from bench.motion.gripper import Gripper
from bench.motion.player import MotionLock, Player
from bench.motion.stations import StationPlanner, load_or_plan


def getch() -> str:
    import termios, tty
    fd = sys.stdin.fileno(); old = termios.tcgetattr(fd)
    try:
        tty.setraw(fd); return sys.stdin.read(1)
    finally:
        termios.tcsetattr(fd, termios.TCSADRAIN, old)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--backend", choices=["sim", "real"], default="sim")
    ap.add_argument("role", choices=["pourer", "transfer"])
    ap.add_argument("station")
    args = ap.parse_args()
    cfg = load()
    if args.backend == "sim":
        from bench.hal.sim import make_sim_bench
        b = make_sim_bench(cfg)
    else:
        from bench.hal.real import make_real_bench
        b = make_real_bench(cfg)
    b.connect()
    plans = load_or_plan(cfg)
    plan = plans[f"{args.role}:{args.station}"]
    planner = StationPlanner(cfg)
    arm = planner.kin[args.role]
    player = Player(b, args.role, MotionLock(), cfg, speed_scale=0.5)
    grip = Gripper(b, args.role, cfg)
    grip.open(wide=(plan.grasp == "top_down"))
    for q in (plan.carry.q, plan.lift.q, plan.pre.q, plan.grasp_pose.q):
        player.move_to(q, 30)
    q = np.array(plan.grasp_pose.q)
    target = arm.grasp_pos(q)
    axis = arm.beaker_axis(q, plan.grasp)
    offset = np.zeros(3)
    print(__doc__)
    keys = {"w": (0, 2), "s": (0, -2), "a": (1, 2), "d": (1, -2), "r": (2, 2), "f": (2, -2)}
    while True:
        k = getch()
        if k == "q":
            return 0
        if k.lower() in keys:
            i, d = keys[k.lower()]
            d = d if k.islower() else d / 4
            offset[i] += d
            res = arm.ik(target + offset, axis, plan.grasp, q0=q) if plan.grasp == "side" \
                else arm.ik_topdown(target + offset, q0=q)
            q = res.q_deg
            player.move_to(q, 15, settle_tol=1.5, settle_timeout=1.0)
            print(f"offset {offset} mm  margin {res.margin_deg:.1f} ({res.binding})")
        elif k == "c":
            print("grasp:", grip.close())
        elif k == "o":
            grip.open(wide=(plan.grasp == "top_down"))
        elif k == "p":
            print({j: round(v, 1) for j, v in b.arms[args.role].read_positions().items()})
        elif k in ("\r", "\n"):
            doc = yaml.safe_load(BENCH_YAML.read_text())
            doc.setdefault("calibration", {}).setdefault("station_offsets_mm", {})[
                f"{args.role}:{args.station}"] = [float(v) for v in offset]
            BENCH_YAML.write_text("# GENERATED by software/scripts/make_bench_config.py - see meta.note\n"
                                  + yaml.safe_dump(doc, sort_keys=False, default_flow_style=None, width=100))
            print(f"saved offset {offset} for {args.role}:{args.station}; re-plan with "
                  f"`python3 -c 'from bench.motion.stations import load_or_plan; load_or_plan(force=True)'`")


if __name__ == "__main__":
    raise SystemExit(main())
