"""Generate review/records/cdr_minutes.md from review/records/cdr_record.json.

Run:  python analysis/make_minutes.py
"""
import json, os, re
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REC = os.path.join(ROOT, "review", "records", "cdr_record.json")
OUT = os.path.join(ROOT, "review", "records", "cdr_minutes.md")


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def main():
    with open(REC, encoding="utf-8") as f:
        d = json.load(f)
    ruling = d["ruling"]
    items, rejected = ruling["action_items"], ruling["rejected"]

    def rulings_for(fid):
        pat = re.compile(r"(?<![A-Z0-9-])%s(?![0-9])" % re.escape(fid))
        ids = [a["id"] for a in items if pat.search(a["decision"])]
        if not ids:
            ids = [a["id"] for a in items if pat.search(a["change"])]
        rej = [r["id"] for r in rejected if pat.search(r["id"])]
        return ids, rej

    L = ["# CDR minutes — Wet Lab Bench v2, 2026-10-14", "",
         "Generated by `python analysis/make_minutes.py` from [cdr_record.json](cdr_record.json). "
         "Full ruling text: [cdr_ruling.md](cdr_ruling.md). Do not edit by hand.", "",
         "## Attendees", "",
         "| Role | Discipline | Part in the review |", "|---|---|---|",
         "| Chief engineer (chair) | all | Ran spot-checks and ruled on every finding |"]
    for t in d["threads"]:
        disc = t["discipline"]
        L.append("| Senior reviewer | %s | Raised %d findings, wrote the rebuttals |" % (disc, len(t["findings"])))
        L.append("| Design owner | %s | Answered each finding (defence)%s |" % (
            disc, ", final word on %s" % ", ".join(x["id"] for x in t["final"]) if t["final"] else ""))
    L.append("")
    L.append("Process (per review/BRIEF.md): reviewer finding → owner defence → reviewer rebuttal "
             "(RESOLVED or ESCALATE) → owner final word on escalations → chief engineer ruling.")
    L.append("")
    n_find = sum(len(t["findings"]) for t in d["threads"])
    L.append("## Outcome in brief")
    L.append("")
    L.append("- %d findings reviewed; %d action items (CDR-xx); %d rejected sub-requirements; nothing rejected outright." % (
        n_find, len(items), len(rejected)))
    pc = Counter(a["priority"] for a in items)
    L.append("- Action items by priority: " + ", ".join("%s %d" % (k, pc[k]) for k in sorted(pc)) +
             "; %d require a reprint." % sum(a["reprint"] for a in items))
    esc = [x["id"] for t in d["threads"] for x in t["rebuttal"] if x["status"] == "ESCALATE"]
    L.append("- Escalated to the chief engineer: %s." % (", ".join(esc) or "none"))
    L.append("")

    for t in d["threads"]:
        disc = t["discipline"]
        dfn = {x["id"]: x for x in t["defense"]}
        reb = {x["id"]: x for x in t["rebuttal"]}
        sev = Counter(x["severity"] for x in t["findings"])
        L.append("## %s" % disc.capitalize())
        L.append("")
        L.append("%d findings (%s)." % (len(t["findings"]), ", ".join("%s %d" % (k, sev[k]) for k in ("BLOCKER", "MAJOR", "MINOR") if sev[k])))
        L.append("")
        L.append("| Finding | Severity | Title | Owner position | Reviewer status | Final ruling |")
        L.append("|---|---|---|---|---|---|")
        for f in t["findings"]:
            ids, rej = rulings_for(f["id"])
            fr = ", ".join(ids) if ids else "-"
            if rej:
                fr += " (part rejected)"
            L.append("| %s | %s | %s | %s | %s | %s |" % (
                f["id"], f["severity"], cell(f["title"]), dfn.get(f["id"], {}).get("position", "-"),
                reb.get(f["id"], {}).get("status", "-"), fr))
        L.append("")

    L.append("## Action items")
    L.append("")
    L.append("| ID | Discipline | Priority | Reprint | Decision | Parts / docs |")
    L.append("|---|---|---|---|---|---|")
    for a in items:
        L.append("| %s | %s | %s | %s | %s | %s |" % (a["id"], a["discipline"], a["priority"], "yes" if a["reprint"] else "no",
                                                   cell(a["decision"]), cell(a["parts_or_docs"])))
    L.append("")
    L.append("## Rejected")
    L.append("")
    L.append("| Finding (part) | Reason |")
    L.append("|---|---|")
    for r in rejected:
        L.append("| %s | %s |" % (cell(r["id"]), cell(r["reason"])))
    L.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L))
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
